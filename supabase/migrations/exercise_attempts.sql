-- One record per try ("sitting") of an exercise.
--
--   user_progress       one row per student per exercise: best score, status (unchanged)
--   exercise_attempts   NEW: one row per try: attempt number, start/submit time, correct/total
--   question_attempts   one row per graded item (question, blank, drop zone, region, field),
--                       now pointing at its try through attempt_id
--
-- Writes go through save_exercise_attempt(), which the browser calls in batches (every ~10
-- answers, when the tab is hidden, and on submit). Grading still happens in the browser.
-- Review-queue answers are not part of a try: they are stored with source = 'review'.

BEGIN;

-- Old rows used a different format per exercise type (q*100+blank, "q1_zone0", comma-joined
-- dropdowns) and can't be grouped into tries. The project is new, so start clean.
DELETE FROM public.question_attempts;

-- ---------------------------------------------------------------------------
-- exercise_attempts
-- ---------------------------------------------------------------------------
CREATE TABLE public.exercise_attempts (
  id uuid PRIMARY KEY,  -- generated by the browser so a resumed try keeps its id
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  exercise_id uuid NOT NULL REFERENCES public.exercises(id) ON DELETE CASCADE,
  attempt_number integer NOT NULL CHECK (attempt_number >= 1),
  status text NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'submitted')),
  correct_count integer NOT NULL DEFAULT 0,  -- kept in sync by triggers on question_attempts
  total_count integer NOT NULL DEFAULT 0,
  score integer GENERATED ALWAYS AS (
    CASE WHEN total_count > 0 THEN round(100.0 * correct_count / total_count)::integer END
  ) STORED,
  started_at timestamptz NOT NULL DEFAULT now(),
  submitted_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT exercise_attempts_user_exercise_number_key UNIQUE (user_id, exercise_id, attempt_number)
);

-- Teacher reports read by exercise; student lookups use the unique key above
CREATE INDEX exercise_attempts_exercise_user_idx ON public.exercise_attempts (exercise_id, user_id);

CREATE TRIGGER update_exercise_attempts_updated_at
  BEFORE UPDATE ON public.exercise_attempts
  FOR EACH ROW EXECUTE FUNCTION public.update_updated_at_column();

ALTER TABLE public.exercise_attempts ENABLE ROW LEVEL SECURITY;

CREATE POLICY exercise_attempts_read ON public.exercise_attempts
  FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR public.is_staff(auth.uid()));
CREATE POLICY exercise_attempts_own_write ON public.exercise_attempts
  FOR ALL TO authenticated
  USING (user_id = auth.uid()) WITH CHECK (user_id = auth.uid());
CREATE POLICY exercise_attempts_staff_write ON public.exercise_attempts
  FOR ALL TO authenticated
  USING (public.is_staff(auth.uid())) WITH CHECK (public.is_staff(auth.uid()));

REVOKE ALL ON public.exercise_attempts FROM anon;

-- ---------------------------------------------------------------------------
-- question_attempts: belong to a try, one consistent shape for every type
-- ---------------------------------------------------------------------------
ALTER TABLE public.question_attempts
  ADD COLUMN attempt_id uuid REFERENCES public.exercise_attempts(id) ON DELETE CASCADE,
  ADD COLUMN source text NOT NULL DEFAULT 'exercise' CHECK (source IN ('exercise', 'review')),
  -- Which part of the question: '' for single-answer questions, 'blank0', 'dd1', a drop-zone id...
  ADD COLUMN item_key text NOT NULL DEFAULT '',
  ADD COLUMN item_index integer NOT NULL DEFAULT 0,
  DROP COLUMN attempt_number;  -- now exercise_attempts.attempt_number

-- Always milliseconds (writers used to mix ms and seconds)
ALTER TABLE public.question_attempts RENAME COLUMN response_time TO response_ms;

ALTER TABLE public.question_attempts
  ALTER COLUMN user_id SET NOT NULL,
  ALTER COLUMN exercise_id SET NOT NULL,
  ALTER COLUMN exercise_type SET NOT NULL,
  ALTER COLUMN manually_overridden SET NOT NULL,
  ALTER COLUMN created_at SET NOT NULL,
  ADD CONSTRAINT question_attempts_source_attempt_check
    CHECK ((source = 'exercise') = (attempt_id IS NOT NULL)),
  -- One row per item per try; saving the same item again updates it
  ADD CONSTRAINT question_attempts_attempt_item_key UNIQUE (attempt_id, question_id, item_key);

COMMENT ON COLUMN public.question_attempts.question_index IS 'Position of the question in the exercise (0-based)';
COMMENT ON COLUMN public.question_attempts.item_index IS 'Position of the item inside its question (0-based)';

-- Latest result per item (review queue) and per-student lookups.
-- Covers the old (user_id) and (user_id, exercise_id) indexes.
CREATE INDEX question_attempts_user_latest_idx
  ON public.question_attempts (user_id, exercise_id, question_id, item_key, created_at DESC);
DROP INDEX IF EXISTS public.idx_question_attempts_user_id;
DROP INDEX IF EXISTS public.idx_question_attempts_user_exercise;

-- ---------------------------------------------------------------------------
-- Keep exercise_attempts.correct_count / total_count in sync (saves and teacher overrides)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.question_attempts_refresh_counts()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  UPDATE exercise_attempts a
  SET correct_count = c.correct, total_count = c.total
  FROM (
    SELECT q.attempt_id,
           count(*) FILTER (WHERE q.is_correct) AS correct,
           count(*) AS total
    FROM question_attempts q
    WHERE q.attempt_id IN (SELECT DISTINCT r.attempt_id FROM changed_rows r WHERE r.attempt_id IS NOT NULL)
    GROUP BY q.attempt_id
  ) c
  WHERE a.id = c.attempt_id;
  RETURN NULL;
END;
$$;

CREATE TRIGGER question_attempts_counts_after_insert
  AFTER INSERT ON public.question_attempts
  REFERENCING NEW TABLE AS changed_rows
  FOR EACH STATEMENT EXECUTE FUNCTION public.question_attempts_refresh_counts();

CREATE TRIGGER question_attempts_counts_after_update
  AFTER UPDATE ON public.question_attempts
  REFERENCING NEW TABLE AS changed_rows
  FOR EACH STATEMENT EXECUTE FUNCTION public.question_attempts_refresh_counts();

-- ---------------------------------------------------------------------------
-- save_exercise_attempt: create the try if needed, upsert its items, optionally submit.
-- p_attempt_id is generated by the browser. Runs as the caller, so RLS still applies.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.save_exercise_attempt(
  p_exercise_id uuid,
  p_attempt_id uuid,
  p_items jsonb DEFAULT '[]'::jsonb,
  p_started_at timestamptz DEFAULT NULL,
  p_submit boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_type text;
  v_attempt exercise_attempts%ROWTYPE;
  v_tries integer := 0;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not signed in' USING ERRCODE = '42501';
  END IF;
  IF p_attempt_id IS NULL THEN
    RAISE EXCEPTION 'p_attempt_id is required' USING ERRCODE = '22004';
  END IF;

  SELECT e.exercise_type INTO v_type FROM exercises e WHERE e.id = p_exercise_id;
  IF v_type IS NULL THEN
    RAISE EXCEPTION 'Exercise not found' USING ERRCODE = 'P0002';
  END IF;

  LOOP
    SELECT * INTO v_attempt FROM exercise_attempts a WHERE a.id = p_attempt_id FOR UPDATE;
    EXIT WHEN FOUND;

    v_tries := v_tries + 1;
    IF v_tries > 5 THEN
      RAISE EXCEPTION 'Could not create attempt';
    END IF;

    BEGIN
      INSERT INTO exercise_attempts (id, user_id, exercise_id, attempt_number, started_at)
      SELECT p_attempt_id, v_uid, p_exercise_id,
             coalesce(max(a.attempt_number), 0) + 1,
             -- trust the browser's start time only within reason
             least(now(), greatest(coalesce(p_started_at, now()), now() - interval '1 day'))
      FROM exercise_attempts a
      WHERE a.user_id = v_uid AND a.exercise_id = p_exercise_id;
    EXCEPTION WHEN unique_violation THEN
      -- Another tab took this attempt number (or created this id): look again
      NULL;
    END;
  END LOOP;

  IF v_attempt.user_id <> v_uid OR v_attempt.exercise_id <> p_exercise_id THEN
    RAISE EXCEPTION 'Attempt does not belong to this user and exercise' USING ERRCODE = '42501';
  END IF;

  INSERT INTO question_attempts (
    user_id, exercise_id, exercise_type, attempt_id, source,
    question_id, question_index, item_key, item_index,
    selected_answer, correct_answer, is_correct, response_ms
  )
  SELECT v_uid, p_exercise_id, v_type, p_attempt_id, 'exercise',
         i.question_id, i.question_index, coalesce(i.item_key, ''), coalesce(i.item_index, 0),
         i.selected_answer, i.correct_answer, coalesce(i.is_correct, false), i.response_ms
  FROM jsonb_to_recordset(coalesce(p_items, '[]'::jsonb)) AS i(
    question_id text, question_index integer, item_key text, item_index integer,
    selected_answer text, correct_answer text, is_correct boolean, response_ms integer
  )
  WHERE i.question_id IS NOT NULL
  ON CONFLICT ON CONSTRAINT question_attempts_attempt_item_key DO UPDATE SET
    question_index = excluded.question_index,
    item_index = excluded.item_index,
    selected_answer = excluded.selected_answer,
    correct_answer = excluded.correct_answer,
    is_correct = excluded.is_correct,
    response_ms = excluded.response_ms
  WHERE NOT question_attempts.manually_overridden;  -- a teacher's override wins

  IF p_submit THEN
    UPDATE exercise_attempts
    SET status = 'submitted', submitted_at = coalesce(submitted_at, now())
    WHERE id = p_attempt_id;
  END IF;

  RETURN jsonb_build_object('attempt_id', v_attempt.id, 'attempt_number', v_attempt.attempt_number);
END;
$$;

REVOKE ALL ON FUNCTION public.save_exercise_attempt(uuid, uuid, jsonb, timestamptz, boolean) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.save_exercise_attempt(uuid, uuid, jsonb, timestamptz, boolean) TO authenticated;

-- ---------------------------------------------------------------------------
-- Latest result per item, across tries and review answers. Used by the review queue so it
-- reads only the current wrong items instead of a student's whole history.
-- security_invoker: the caller's RLS on question_attempts applies.
-- ---------------------------------------------------------------------------
CREATE VIEW public.question_latest_results
WITH (security_invoker = true) AS
SELECT DISTINCT ON (q.user_id, q.exercise_id, q.question_id, q.item_key)
  q.user_id, q.exercise_id, q.exercise_type, q.question_id, q.item_key,
  q.is_correct, q.created_at
FROM public.question_attempts q
ORDER BY q.user_id, q.exercise_id, q.question_id, q.item_key, q.created_at DESC;

REVOKE ALL ON public.question_latest_results FROM anon;
GRANT SELECT ON public.question_latest_results TO authenticated;

COMMIT;
